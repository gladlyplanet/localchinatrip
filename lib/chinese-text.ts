export function toTraditionalChinese(value: string) {
  return [...value]
    .map((character) => simplifiedToTraditional[character] ?? character)
    .join("")
    .replace(/這里/g, "這裡")
    .replace(/那里/g, "那裡")
    .replace(/哪里/g, "哪裡");
}
